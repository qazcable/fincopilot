export function guideTopic(id: string) {
  return GUIDE_TOPICS.find(t => t.id === id) ?? null;
}

function escapeHtml(text: string) {
  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/** Тема для Telegram (HTML) */
export function guideTopicHtml(topic: GuideTopic) {
  return [
    `${topic.emoji} <b>${escapeHtml(topic.title)}</b>`,
    "",
    `<b>Что это:</b> ${escapeHtml(topic.what)}`,
    `<b>Зачем:</b> ${escapeHtml(topic.why)}`,
    "",
    "<b>Как работает:</b>",
    ...topic.how.map((step, i) => `${i + 1}. ${escapeHtml(step)}`),
  ].join("\n");
}

